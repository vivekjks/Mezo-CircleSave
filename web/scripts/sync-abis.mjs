// Regenerates typed ABIs + deployment addresses from the Foundry build.
// Usage: node scripts/sync-abis.mjs  (run `forge build` in ../contracts first)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..", "contracts");
const contracts = ["SavingsCircle", "CircleFactory", "CircleGovernor", "CircleLens", "MusdFaucet"];

let out = "// Generated by scripts/sync-abis.mjs. Do not edit by hand.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const key = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${key} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(import.meta.dirname, "..", "src", "lib", "contracts", "abis.ts"), out);

const dep = JSON.parse(readFileSync(join(root, "deployments", "31611.json"), "utf8"));
const addr = `// Generated by scripts/sync-abis.mjs from contracts/deployments/31611.json.

export const deployment = {
  chainId: ${dep.chainId},
  deployBlock: ${dep.deployBlock}n,
  musd: "${dep.musd}",
  factory: "${dep.factory}",
  governor: "${dep.governor}",
  lens: "${dep.lens}",
  faucet: "${dep.faucet}",
  implementation: "${dep.implementation}",
} as const;
`;
writeFileSync(join(import.meta.dirname, "..", "src", "lib", "contracts", "deployment.ts"), addr);
console.log("ABIs and deployment synced.");
